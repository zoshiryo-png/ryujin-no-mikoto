// 今日の日付からシード値を作る（同じ日は同じメッセージ）
function todaySeed(): number {
  const today = new Date()
  return (
    today.getFullYear() * 10000 +
    (today.getMonth() + 1) * 100 +
    today.getDate()
  )
}

export function getTodayMessage(attribute: Attribute): string {
  const seed = todaySeed()
  const messages = MESSAGES[attribute]
  return messages[seed % messages.length]
}

export function getTodayKey(): string {
  const today = new Date()
  return `${today.getFullYear()}-${String(today.getMonth() + 1).padStart(
    2,
    '0'
  )}-${String(today.getDate()).padStart(2, '0')}`
}

// 月日を漢数字で（例：「五月二十九日」）
const KANJI_DIGITS = ['', '一', '二', '三', '四', '五', '六', '七', '八', '九']
const KANJI_MONTHS = [
  '',
  '一月',
  '二月',
  '三月',
  '四月',
  '五月',
  '六月',
  '七月',
  '八月',
  '九月',
  '十月',
  '十一月',
  '十二月',
]

function dayToKanji(d: number): string {
  if (d < 10) return `${KANJI_DIGITS[d]}日`
  if (d === 10) return '十日'
  if (d < 20) return `十${KANJI_DIGITS[d - 10]}日`
  if (d === 20) return '二十日'
  if (d < 30) return `二十${KANJI_DIGITS[d - 20]}日`
  if (d === 30) return '三十日'
  return `三十${KANJI_DIGITS[d - 30]}日`
}

export function todayInKanji(): string {
  const today = new Date()
  return `${KANJI_MONTHS[today.getMonth() + 1]}${dayToKanji(today.getDate())}`
}
